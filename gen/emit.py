#!/usr/bin/env python3
"""Emit art.ts from art.json: generated smooth gradient art registry.

ArtEntry evolves: { runs: [[colorIdx, text], ...][]; colors: string[]; color?: string }
`lines` stays for compact/legacy; generated entries keep a plain-glyph line copy
for fallback. Session glyphs stay as unicode marks.
"""
