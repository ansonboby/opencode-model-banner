def ts_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def ts_runs(runs):
    # runs: [[idx, text], ...][] -> "[[0,\"███\"],[1,\"▀\"],...]"
    parts = []
    for run in runs:
        segs = ','.join(f'[{i},{ts_str(t)}]' for i, t in run)
        parts.append(f'[{segs}]')
    return '[' + ','.join(parts) + ']'

def ts_colors(colors):
    return '[' + ','.join(ts_str(c) for c in colors) + ']'

out = []
out.append('// Generated by /tmp/artgen — DO NOT EDIT BY HAND.')
out.append('// Per-brand smooth gradient half-block art (official brand logos,')
out.append('// supersampled + density-packed). Data model: runs+colors.')
out.append('')
out.append('export type ArtEntry = {')
out.append('  lines: string[]')
out.append('  // Generated smooth art: per-line [paletteIdx, text] segments + shared palette.')
out.append('  runs?: [number, string][][]')
out.append('  colors?: string[]')
out.append('  color?: string')
out.append('  compact?: string[]')
out.append('}')
out.append('')
out.append('export type ModelKey = { providerID: string; modelID: string }')
out.append('')

entries = []
for brand, info in BRAND_MAP.items():
    if brand not in d:
        continue
    art = d[brand]
    # lines = plain glyph rows (no color) for fallback/compact derivations
    lines = [''.join(t for _, t in run) for run in art['runs']]
    lines_join = chr(10).join('    ' + ts_str(l) + ',' for l in lines)
    color = art['colors'][0]  # top of gradient = brand color
    entry = f'''const {brand}Art: ArtEntry = {{
  color: {ts_str(color)},
  colors: {ts_colors(art['colors'])},
  runs: {ts_runs(art['runs'])},
  lines: [
{lines_join}
  ],
}}'''
    entries.append(entry)

out.append('// ---------------------------------------------------------------------------')
out.append('// Generated brand art (official logos → smooth gradient half-blocks)')
out.append('// ---------------------------------------------------------------------------')
out.append('')
out.append(chr(10).join(entries))
out.append('')

# registry mapping
out.append('export const registry = {')
out.append('  models: {')
model_lines = []
for brand, info in BRAND_MAP.items():
    if brand not in d:
        continue
    var = brand + 'Art'
    for g in info['models']:
        model_lines.append(f'    {ts_str(g)}: {var},')
out.append(chr(10).join(model_lines))
out.append('  },')
out.append('  providers: {')
prov_lines = []
for brand, info in BRAND_MAP.items():
    if brand not in d:
        continue
    var = brand + 'Art'
    for p in info['providers']:
        prov_lines.append(f'    {ts_str(p)}: {var},')
# default = opencode art
prov_lines.append('    default: opencodeArt,')
out.append(chr(10).join(prov_lines))
out.append('  },')
out.append('} as const')
out.append('')

open('/tmp/artgen/art_gen.ts', 'w').write(chr(10).join(out) + chr(10))
print('emitted', len(entries), 'entries')
