// Render a short label as FIGlet-block art (max 12 chars; then truncates).
function figlet(label: string): { lines: string[]; width: number } {
  const raw = label.toUpperCase().replace(/[^A-Z0-9.\-_ ]/g, "").slice(0, 12)
  const chars = Array.from(raw)
  const rows = ["", "", "", "", ""]
  let width = 0
  for (const ch of chars) {
    const glyph = FONT[ch] ?? FONT["-"]
    const glyphRows = glyph.length > 5 ? glyph : [...glyph, ...Array(5 - glyph.length).fill("")]
    for (let i = 0; i < 5; i++) rows[i] += (glyphRows[i] ?? "") + " "
    width += (glyphRows[0]?.length ?? 0) + 1
  }
  return { lines: rows, width }
}

// Match art for a model, with the fallback chain: exact → glob → provider → default.
function matchArt(providerID: string, modelID: string, displayName: string): { entry: ArtEntry; name: string } {
  const full = `${providerID}/${modelID}`
  // 1. exact + glob model keys
  const modelKeys = [full, modelID, `${providerID}/*`]
  for (const key of modelKeys) {
    const direct = registry.models[key]
    if (direct) return { entry: direct, name: nameFor(displayName, modelID) }
    if (key.endsWith("*")) {
      const prefix = key.slice(0, -1)
      for (const [pattern, entry] of Object.entries(registry.models)) {
        if (pattern.startsWith(prefix) && pattern.endsWith("*")) {
          const target = pattern.slice(0, -1)
          if (full.startsWith(target) || modelID.startsWith(target)) {
            return { entry, name: nameFor(displayName, modelID) }
          }
        }
      }
    }
  }
  // Glob-model keys where pattern prefix matches full id (e.g. deepseek/*, glm*)
  for (const [pattern, entry] of Object.entries(registry.models)) {
    if (!pattern.endsWith("*")) continue
    const target = pattern.slice(0, -1)
    if (full.startsWith(target) || modelID.startsWith(target)) {
      return { entry, name: nameFor(displayName, modelID) }
    }
  }
  // 2. provider keys
  const providerKey = providerID.toLowerCase()
  const byProvider = registry.providers[providerKey]
  if (byProvider) return { entry: byProvider, name: nameFor(displayName, modelID) }
  // provider substring (z-ai in glm-5.3, etc.)
  const brand = Object.keys(registry.providers).find(
    (key) => providerKey.includes(key) || modelID.toLowerCase().includes(key),
  )
  if (brand) return { entry: registry.providers[brand]!, name: nameFor(displayName, modelID) }
  // 3. FIGlet of the display name in a soft brand color (unknown models)
  const name = nameFor(displayName, modelID)
  const fig = figlet(name.replace(/[^A-Za-z0-9.\-_ ]/g, "").slice(0, 12))
  return {
    entry: { lines: fig.lines, color: "#8888AA", compact: [name] },
    name,
  }
}

