function nameFor(displayName: string, modelID: string): string {
  const clean = displayName || modelID
  // strip org prefix like "deepseek/deepseek-v4-flash" → "DeepSeek V4 Flash"
  const last = clean.split("/").pop() ?? clean
  const spaced = last.replace(/[-_]/g, " ")
  return spaced
    .split(" ")
    .filter((token) => token.length > 0)
    .map((token) => BRAND_TOKENS[token.toLowerCase()] ?? (token === token.toLowerCase() ? token[0]!.toUpperCase() + token.slice(1) : token))
    .join(" ")
    .trim()
}
// ---------------------------------------------------------------------------
// Color helpers (RGBA from hex; gradient interpolation)
// ---------------------------------------------------------------------------

type RGBA = { r: number; g: number; b: number; a: number }

function hexToRgba(hex: string): RGBA | undefined {
  const value = hex.replace("#", "").trim()
  if (value.length !== 6 && value.length !== 8) return undefined
  const num = Number.parseInt(value, 16)
  if (Number.isNaN(num)) return undefined
  if (value.length === 6) return { r: (num >> 16) & 255, g: (num >> 8) & 255, b: num & 255, a: 255 }
  return { r: (num >>> 24) & 255, g: (num >>> 16) & 255, b: (num >>> 8) & 255, a: num & 255 }
}

function mix(a: RGBA, b: RGBA, t: number): RGBA {
  return {
    r: Math.round(a.r + (b.r - a.r) * t),
    g: Math.round(a.g + (b.g - a.g) * t),
    b: Math.round(a.b + (b.b - a.b) * t),
    a: 255,
  }
}

function toHex(color: RGBA): string {
  const clamp = (value: number) => Math.max(0, Math.min(255, Math.round(value))).toString(16).padStart(2, "0")
  return `#${clamp(color.r)}${clamp(color.g)}${clamp(color.b)}`
}

/** Vertical gradient from brand color toward background (mockup style: dark base, bright crest). */
function gradientStops(brand: RGBA, background: RGBA, rows: number): RGBA[] {
  const stops: RGBA[] = []
  for (let i = 0; i < rows; i++) {
    const t = rows <= 1 ? 1 : i / (rows - 1)
    // bright at the crest (top), fading into the background at the tail
    const lift = 0.35 + 0.65 * (1 - t)
    stops.push(mix(background, brand, Math.min(1, lift)))
  }
  return stops
}

