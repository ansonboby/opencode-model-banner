type ModelRefLite = { providerID: string; modelID: string }

function parseModel(value: string): ModelRefLite | undefined {
  const index = value.indexOf("/")
  if (index === -1) return { providerID: value, modelID: "" }
  return { providerID: value.slice(0, index), modelID: value.slice(index + 1) }
}

type StatePaths = { readonly path: { readonly state: string } }
type ModelJson = { recent?: Array<{ providerID: string; modelID: string }> }
type FsLike = { existsSync(path: string): boolean; readFileSync(path: string, encoding: "utf8"): string }
type PathLike = { join(...parts: string[]): string }

function readModelJson(state: StatePaths): ModelRefLite | undefined {
  try {
    // Plugins run under Bun: sync require is available at runtime.
    const fs = require("node:fs") as FsLike
    const path = require("node:path") as PathLike
    const file = path.join(state.path.state, "model.json")
    if (!fs.existsSync(file)) return undefined
    const raw = JSON.parse(fs.readFileSync(file, "utf8")) as ModelJson
    const first = raw.recent?.[0]
    return first ? { providerID: first.providerID, modelID: first.modelID } : undefined
  } catch {
    return undefined
  }
}

function isModelValid(providers: ReadonlyArray<{ id: string; models: Record<string, unknown> }>, ref: ModelRefLite | undefined): boolean {
  if (!ref || !ref.modelID) return false
  return providers.some((provider) => provider.id === ref.providerID && provider.models[ref.modelID] !== undefined)
}

function resolveCurrentModel(api: TuiPluginApi, modelTick: () => number, onModelFileChange: () => void): () => ModelRefLite | undefined {
  // Re-read model.json when the model picker or prompt cycle writes it, so the
  // banner swaps live on ctrl+x m switches.
  try {
    const fs = require("node:fs") as FsLike & { watchFile(path: string, listener: () => void): void; unwatchFile(path: string, listener?: () => void): void }
    const path = require("node:path") as PathLike
    const file = path.join(api.state.path.state, "model.json")
    const listener = () => onModelFileChange()
    fs.watchFile(file, { interval: 500 }, listener)
    api.lifecycle.onDispose(() => {
      fs.unwatchFile(file, listener)
    })
  } catch {
    // watch unavailable — banner stays static for this session
  }

  return createMemo(() => {
    modelTick() // dependency: re-resolve when model.json changes
    const providers = api.state.provider
    // 1. config `model` (opencode.json)
    const configModel = api.state.config.model
    if (typeof configModel === "string") {
      const ref = parseModel(configModel)
      if (isModelValid(providers, ref)) return ref
    }
    // 2. last used (state/model.json recent[0]) — matches core fallback chain
    const recent = readModelJson(api.state)
    if (isModelValid(providers, recent)) return recent
    // 3. first provider's default / first model
    const provider = providers[0]
    if (!provider) return undefined
    const firstModel = Object.values(provider.models)[0] as { id?: string } | undefined
    const modelID = firstModel?.id ?? Object.keys(provider.models)[0]
    if (!modelID) return undefined
    return { providerID: provider.id, modelID }
  })
}

function displayName(api: TuiPluginApi, ref: ModelRefLite | undefined): string {
  if (!ref) return ""
  const provider = api.state.provider.find((item) => item.id === ref.providerID)
  const info = provider?.models[ref.modelID] as { name?: string } | undefined
  return info?.name ?? ref.modelID
}

