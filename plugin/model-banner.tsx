function HomeBanner(props: { api: TuiPluginApi; theme: TuiSlotContext["theme"]; ref: () => ModelRefLite | undefined }) {
  const brand = createMemo(() => {
    const ref = props.ref()
    if (!ref) return undefined
    const name = displayName(props.api, ref)
    const matched = matchArt(ref.providerID, ref.modelID, name)
    return { matched, ref, name }
  })

  // Derived entirely from the memo, so a model switch re-renders everything.
  const view = createMemo(() => {
    const value = brand()
    if (!value) return undefined
    const { matched, ref } = value
    const name = matched.name
    const theme = props.theme.current
    const bg = { r: theme.background.r * 255, g: theme.background.g * 255, b: theme.background.b * 255, a: 255 }
    const brandHex = matched.entry.color ?? "#8888AA"
    const brandColor = hexToRgba(brandHex)
    const allLines = matched.entry.lines
    // Generated smooth art: runs+colors. Legacy entries: plain lines.
    const runs: Array<Array<[number, string]>> | undefined = matched.entry.runs
    const palette = matched.entry.colors
    // Cap art height to ~40% of the terminal so the prompt stays visible.
    const maxRows = Math.max(4, Math.floor(props.api.renderer.height * 0.4))
    const keep = (n: number) => {
      if (n <= maxRows) return Array.from({ length: n }, (_, i) => i)
      const step = Math.ceil(n / maxRows)
      return Array.from({ length: n }, (_, i) => i)
        .filter(i => i === 0 || i === n - 1 || i % step !== 0)
    }
    const rowIdx = keep(runs ? runs.length : allLines.length)
    const stops = gradientStops(brandColor ?? { r: 120, g: 120, b: 160, a: 255 }, bg, rowIdx.length)
    return { name, ref, bg, brandColor, brandHex, runs, palette, allLines, rowIdx, stops, maxRows }
  })

  return (
    <Show when={view()}>
      <box flexDirection="column" alignItems="center" flexShrink={1} minHeight={0}>
        <box flexDirection="column" alignItems="center">
          <Index each={view()!.rowIdx}>
            {(row, i) => (
              <box flexDirection="row" flexShrink={0} minHeight={0}>
                {view()!.runs
                  ? (view()!.runs![i] ?? []).map(([ci, text], j) => (
                      <text fg={view()!.palette?.[ci] ?? view()!.brandHex}>{text}</text>
                    ))
                  : <text fg={toHex(view()!.stops[Math.min(i, view()!.stops.length - 1)]!)}>{view()!.allLines[i]}</text>
                }
              </box>
            )}
          </Index>
        </box>
        <box flexDirection="row" gap={1} paddingTop={0}>
          <text fg={toHex(view()!.brandColor ?? { r: 150, g: 150, b: 180, a: 255 })}>{view()!.name}</text>
          <Show when={view()!.ref?.providerID}>
            <text fg={toHex(mix(view()!.bg, view()!.brandColor ?? { r: 120, g: 120, b: 160, a: 255 }, 0.45))}>
              ({view()!.ref?.providerID})
            </text>
          </Show>
        </box>
      </box>
    </Show>
  )
}

